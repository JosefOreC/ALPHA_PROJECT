test('fallo al guardar conserva los campos y no muestra éxito', async ({ page }) => {
  const api = await mockApi(page, { failWrite: true })
  await page.goto('/?vista=pedidos')
  await page.getByRole('button', { name: 'Registrar pedido', exact: true }).click()
  await fillOrder(page, 'Conservar ante error')
  await page.getByRole('button', { name: 'Registrar pedido', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('No se pudo completar')
  await expect(page.getByLabel('Destinatario *', { exact: true })).toHaveValue('Conservar ante error')
  await expect(page.getByText('Pedido guardado correctamente.', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Modo demostración', { exact: false })).toHaveCount(0)
  expect(api.calls.create).toBe(1)
  expect(api.orders.size).toBe(1)
})

