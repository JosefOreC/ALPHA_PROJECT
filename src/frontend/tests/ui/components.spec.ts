test('el destino se elige por ubicación actual y se ajusta en el mapa antes de guardar',async ({page,context}) => {
  const api = await mockApi(page)
  await stubTiles(page)
  await context.grantPermissions(['geolocation'])
  await context.setGeolocation({latitude:-12.04,longitude:-76.95})
  await page.goto('/?vista=pedidos')
  await page.getByRole('button',{name:'Registrar pedido',exact:true}).click()
  await fillOrder(page)
  await page.getByRole('button',{name:'Usar ubicación actual'}).click()
  await expect(page.getByLabel('Latitud de entrega')).toHaveValue('-12.04')
  await expect(page.getByLabel('Longitud de entrega')).toHaveValue('-76.95')
  const map = page.getByRole('group',{name:'Mapa para seleccionar destino'})
  const canvas = map.locator('.leaflet-container')
  await expect(canvas).toHaveAttribute('data-basemap-ready','true')
  await expect(map.getByTitle('Destino del pedido: arrastra para ajustar')).toBeVisible()
  await canvas.click({position:{x:230,y:110}})
  await expect(page.getByLabel('Latitud de entrega')).not.toHaveValue('-12.04')
  await expect(page.getByLabel('Longitud de entrega')).not.toHaveValue('-76.95')
  const beforeDrag = await page.getByLabel('Longitud de entrega').inputValue()
  const marker = (await map.getByTitle('Destino del pedido: arrastra para ajustar').boundingBox())!
  await page.mouse.move(marker.x+18,marker.y+15)
  await page.mouse.down()
  await page.mouse.move(marker.x+63,marker.y+33,{steps:5})
  await page.mouse.up()
  await expect(page.getByLabel('Longitud de entrega')).not.toHaveValue(beforeDrag)
  const latitude = Number(await page.getByLabel('Latitud de entrega').inputValue())
  const longitude = Number(await page.getByLabel('Longitud de entrega').inputValue())
  expect(api.calls.create).toBe(0)
  await page.getByRole('button',{name:'Registrar pedido',exact:true}).click()
  await expect(page.getByText('Pedido guardado correctamente.')).toBeVisible()
  expect(api.orders.get('NUEVO-FICTICIO')).toMatchObject({latitude,longitude,address:'Dirección ficticia 456',district:'Ate'})
  await page.getByRole('button',{name:'Editar pedido',exact:true}).click()
  await expect(page.getByLabel('Latitud de entrega')).toHaveValue(String(latitude))
  await page.getByRole('button',{name:'Seleccionar en mapa'}).click()
  await expect(page.getByRole('group',{name:'Mapa para seleccionar destino'}).getByTitle('Destino del pedido: arrastra para ajustar')).toBeVisible()
})

test('el destino puede elegirse en el mapa sin permiso de ubicación y corregirse con teclado',async ({page}) => {
  await mockApi(page)
  await stubTiles(page)
  await page.addInitScript(() => Object.defineProperty(navigator,'geolocation',{configurable:true,value:{getCurrentPosition:(_success:unknown,error:(value:{code:number})=>void) => error({code:1})}}))
  await page.goto('/?vista=pedidos')
  await page.getByRole('button',{name:'Registrar pedido',exact:true}).click()
  await page.getByRole('button',{name:'Usar ubicación actual'}).click()
  await expect(page.getByText(/No se concedió permiso de ubicación/)).toBeVisible()
  await page.getByRole('button',{name:'Seleccionar en mapa'}).click()
  const map = page.getByRole('group',{name:'Mapa para seleccionar destino'})
  const canvas = map.locator('.leaflet-container')
  await expect(canvas).toHaveAttribute('data-basemap-ready','true')
  await canvas.click({position:{x:230,y:110}})
  const previous = await page.getByLabel('Longitud de entrega').inputValue()
  const markerX = await map.getByTitle('Destino del pedido: arrastra para ajustar').evaluate(element => element.getBoundingClientRect().x)
  await canvas.focus()
  await canvas.press('ArrowRight')
  await expect.poll(async () => map.getByTitle('Destino del pedido: arrastra para ajustar').evaluate(element => element.getBoundingClientRect().x)).toBeLessThan(markerX-10)
  await map.getByRole('button',{name:'Usar centro del mapa'}).click()
  await expect(page.getByLabel('Longitud de entrega')).not.toHaveValue(previous)
})

